// After `astro build`: write dist/sw.js, a small service worker that keeps the
// site's files in the browser so repeat visits load almost instantly (and the
// page still opens offline).
//  - Files in /_astro/ and /fonts/ never change (their names carry a content
//    hash), so they're served from the cache first; the core CSS, JS and
//    fonts are saved on install.
//  - The page itself (HTML) always tries the network first, so visitors get
//    updates straight away; the cached copy is the offline fallback.
//  - Each build gets its own cache version; old caches are cleared.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, sep, extname } from 'node:path';
import { createHash } from 'node:crypto';

const DIST = 'dist';
const walk = (d) => readdirSync(d, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(d, e.name)) : [join(d, e.name)]));
const files = walk(DIST)
  .filter((f) => !f.endsWith('.br') && !f.endsWith('.gz') && !f.endsWith('sw.js'))
  .map((f) => '/' + relative(DIST, f).split(sep).join('/'));

// Version = hash of every file's name and contents.
const hash = createHash('sha256');
for (const f of files.sort()) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 10);

// Saved on install: what every visit needs (page, styles, scripts, fonts).
const core = ['/', ...files.filter((f) => ['.css', '.js', '.woff2'].includes(extname(f)))];

const sw = `/* Zend service worker (generated by scripts/sw-build.mjs; build ${version}) */
const CACHE = 'zend-${version}';
const CORE = ${JSON.stringify(core)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(CORE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('zend-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return; // e.g. the waitlist sheet: always live

  // Hashed files never change: cache first, fill the cache on first use.
  if (url.pathname.startsWith('/_astro/') || url.pathname.startsWith('/fonts/')) {
    e.respondWith(
      caches.match(req).then(
        (hit) =>
          hit ||
          fetch(req).then((res) => {
            if (res.ok) {
              const copy = res.clone();
              caches.open(CACHE).then((c) => c.put(req, copy));
            }
            return res;
          }),
      ),
    );
    return;
  }

  // Pages: network first (fresh content), each page's cached copy as the
  // offline fallback (the home page if that page was never visited).
  if (req.mode === 'navigate') {
    const key = url.pathname.endsWith('/') && url.pathname !== '/' ? url.pathname.slice(0, -1) : url.pathname;
    e.respondWith(
      fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(key, copy));
          }
          return res;
        })
        .catch(() => caches.match(key).then((hit) => hit || caches.match('/'))),
    );
    return;
  }

  // Anything else (favicon, etc.): cached copy straight away, refreshed behind.
  e.respondWith(
    caches.match(req).then((hit) => {
      const net = fetch(req)
        .then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        })
        .catch(() => hit);
      return hit || net;
    }),
  );
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw: build ${version}, ${core.length} core files precached`);
